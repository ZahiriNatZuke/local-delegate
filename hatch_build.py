"""Hatchling build hook: every wheel carries a ``register.js`` freshly built from ``mod/*.js``.

SDD claude-plugin-and-mods, batch build-mod-in-build. ``register.js`` (the hooks module of the
mod) is generated by ``scripts/build_mod.py`` and not committed, so a build that skipped that step
shipped a plugin without its mod. This hook runs the same ``build()`` on every wheel build
(``uv build``, ``uv tool install .``, ``pip install .``, the wheel built from the sdist, and the
editable install of ``uv sync``), writing ``register.js`` next to its pieces. The wheel target
lists it in ``artifacts`` because ``.gitignore`` keeps it out of the file selection.

``build_mod.py`` is loaded by path, not imported as a module: ``scripts/`` is not a package. The
sdist leaves ``scripts/`` out (it is the repository's workshop), so it force-includes that one
file at its root as ``_build_mod.py``, and a wheel built from the sdist regenerates the module
from there.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

from hatchling.builders.hooks.plugin.interface import BuildHookInterface

#: Where ``build_mod.py`` lives: in the repository, and at the root of the sdist.
BUILD_SCRIPTS = (Path("scripts") / "build_mod.py", Path("_build_mod.py"))
PLUGIN_DIR = Path("src") / "local_delegate" / "resources" / "claude-plugin" / "local-delegate"


def _load_build_mod(root: Path):
    path = next((root / p for p in BUILD_SCRIPTS if (root / p).is_file()), None)
    if path is None:
        raise RuntimeError(f"build_mod.py is missing under {root}: register.js cannot be built")
    spec = importlib.util.spec_from_file_location("_local_delegate_build_mod", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"{path} cannot be loaded")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class ModBuildHook(BuildHookInterface):
    """Writes ``register.js`` before the wheel collects its files."""

    PLUGIN_NAME = "custom"

    def initialize(self, version: str, build_data: dict) -> None:
        root = Path(self.root)
        build_mod = _load_build_mod(root)
        plugin_dir = root / PLUGIN_DIR
        text = build_mod.build(plugin_dir)
        output = plugin_dir / build_mod.OUTPUT_NAME
        output.write_text(text, encoding="utf-8", newline="\n")
